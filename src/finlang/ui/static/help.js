/* FinLang Workbench — per-section help (SOL-112 queue item 9, made real).
 *
 * The ? chips on section titles are rendered by CSS; this wires them: click a
 * titled section to toggle its help. Copy lives here, keyed by page and title
 * prefix. Register rules apply: "can" not "will", no ensures/guarantees, and
 * where behaviour has a cost (audit none, fuzzy matching) the help says so.
 */
"use strict";
(function () {
  const HELP = {
    "index.html": {
      "ENGINE": "The live engine behind every screen. Version comes from /health; “resolved” means the finlang CLI is on this machine’s PATH — every run here shells to it, so the Workbench can never disagree with the terminal.",
    },
    "run.html": {
      "FILES": "Pick the transactions CSV and where the rules come from: a .fin file from disk, a bundled starter pack, or the draft sitting in your Rules editor. If your file uses different header names or European formats, open the locale block below the pickers.",
      "WHAT TO RUN": "Audit records why each row got its category — full keeps the rule, the matched condition and the changes (the rows table needs it for its rule column). Verify checks date, amount and counterparty came out exactly as they went in. Reconcile compares the whole output against a model’s, row by row. Any combination is fine — impact lives on its own screen because the engine refuses to run it alongside these.",
    },
    "rules.html": {
      "1": "The rule’s name, exactly as it will appear in the audit trail against every row it decides. Convention: Area: Subject — e.g. Compliance: Offshore Jurisdictions.",
      "2": "When does the rule fire? Each condition tests one field; all conditions must be true together (AND). Want OR? That’s a second rule with the other pattern. “like” is a case-insensitive wildcard match — *TESCO* means contains.",
      "3": "What the rule does when it fires. category is the main output; flags is append-only (one word, no spaces); exclude marks a row excluded without deleting it.",
      "4": "Exactly the text Insert will append to your file — no magic between the form and the file. Inserting also runs the whole file through the engine’s parser, so a mistake is caught the moment it lands.",
      "WHAT THE ENGINE UNDERSTOOD": "Generated by the engine’s own tokeniser when you Check — the same code that fires the rules produced these sentences, so what they say is what a run will do. If a sentence isn’t what you meant, fix the rule before running anything.",
    },
    "gaps.html": {
      "1": "Two ways in: pick raw data plus the rules to check coverage of (it categorises first, then finds what was missed), or open the disclosure and hand it a categorized.csv you saved from a Run. Either way the line above the button says exactly what was checked against what.",
      "2": "Every counterparty no rule claimed, with how often it appears — ×6 outranks a one-off. Tick the ones worth a rule; raise the threshold on the left to hide rare noise.",
      "3": "Drafting options: the category the new rules should assign, the prefix for their names (so drafted rules are easy to spot later), and fuzzy vs exact matching — fuzzy writes contains-style wildcards and can merge similar counterparties into one rule.",
      "4": "Proposals, not decisions. Append adds them to your Rules editor draft under a dated review comment — you keep, edit or delete each one there, then re-run to watch the gap count fall.",
    },
    "impact.html": {
      "FILES": "Baseline is what runs today; candidate is the proposed change — a file, or the draft from your Rules editor. Both run over the same data and the result is the exact difference between them, row by row.",
      "ONE QUESTION PER RUN": "Impact answers “what changes if I switch rulepacks?” — it expects differences, so running verify (which expects none) or reconcile (which compares against an external system) alongside it would be answering three questions with one run. The engine refuses, and this screen simply doesn’t offer them.",
    },
  };

  const page = (location.pathname.split("/").pop() || "index.html") || "index.html";
  const map = HELP[page];
  if (!map) return;

  document.querySelectorAll(".card > .t").forEach((t) => {
    const text = t.textContent.trim().toUpperCase();
    const key = Object.keys(map).find((k) => text.startsWith(k.toUpperCase()));
    if (!key) { t.classList.add("nohelp"); return; }
    t.style.cursor = "pointer";
    t.setAttribute("title", "click for help");
    t.addEventListener("click", () => {
      const existing = t.parentElement.querySelector(":scope > .helpbox");
      if (existing) { existing.remove(); return; }
      const box = document.createElement("div");
      box.className = "helpbox";
      box.textContent = map[key];
      t.after(box);
    });
  });
})();
